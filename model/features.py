# ---------------------------------------------------------------------------
# Target column
# ---------------------------------------------------------------------------

TARGET: str = "temp_error"
HISTORICAL_TARGET_FEATURE: str = "hist_temp_error"

# ---------------------------------------------------------------------------
# Derived column sets
# ---------------------------------------------------------------------------

REQUIRED_ENCODER_SOURCE_COLUMNS: list[str] = (
    HRRR_KNOWN_REALS + OBS_UNKNOWN_REALS + [TARGET]
)

REQUIRED_DECODER_SOURCE_COLUMNS: list[str] = list(HRRR_KNOWN_REALS)

# ---------------------------------------------------------------------------
# TFT time_varying_known/unknown_reals (training and inference must match)
# These are the lists passed directly to TimeSeriesDataSet / TftModel.
# ---------------------------------------------------------------------------

# Calendar encoding columns prepended to HRRR_KNOWN_REALS for the TFT encoder.
_TFT_TIME_ENCODING: list[str] = [
    "local_idx",
    "sin_hour", "cos_hour", "sin_doy", "cos_doy",
]

TFT_KNOWN_REALS: list[str] = _TFT_TIME_ENCODING + HRRR_KNOWN_REALS
TFT_UNKNOWN_REALS: list[str] = (
    list(OBS_UNKNOWN_REALS) + [HISTORICAL_TARGET_FEATURE]
)

# ---------------------------------------------------------------------------
# Model-generated columns (added by the pipeline, not sourced from raw data)
# Note: some entries here (local_idx, sin_hour, cos_hour, sin_doy, cos_doy) also
# appear in TFT_KNOWN_REALS.  The overlap is intentional -- they are generated by
# the pipeline AND consumed as known-real inputs by TFT.  The two lists are not
# expected to be disjoint.
# ---------------------------------------------------------------------------

MODEL_GENERATED_COLUMNS: list[str] = [
    "time_idx",
    "local_idx",
    "month",
    "day_of_year",
    "hour_of_day",
    "sin_hour",
    "cos_hour",
    "sin_doy",
    "cos_doy",
    "init_time_str",
    "Node_ID",
]


def add_model_features(
    df: pd.DataFrame,
    start_idx: int,
    init_utc: pd.Timestamp,
    station_id: str,
) -> pd.DataFrame:
    """Add canonical TFT time/index features used by training and inference."""
    df = df.copy()
    n = len(df)
    idx = list(range(start_idx, start_idx + n))
    df["time_idx"] = idx
    df["local_idx"] = idx

    if "valid_time" not in df.columns:
        raise ValueError(
            "DataFrame passed to add_model_features must have a 'valid_time' column"
        )
    vt = pd.to_datetime(df["valid_time"], utc=True)
    hour = vt.dt.hour.values
    doy = vt.dt.day_of_year.values
    df["month"] = vt.dt.month.values
    df["day_of_year"] = doy
    df["hour_of_day"] = hour
    df["sin_hour"] = np.sin(2 * np.pi * hour / 24).astype("float32")
    df["cos_hour"] = np.cos(2 * np.pi * hour / 24).astype("float32")
    df["sin_doy"] = np.sin(2 * np.pi * doy / 365).astype("float32")
    df["cos_doy"] = np.cos(2 * np.pi * doy / 365).astype("float32")
    df["init_time_str"] = str(
        init_utc.tz_localize("UTC") if init_utc.tzinfo is None else init_utc.tz_convert("UTC")
    )
    df["Node_ID"] = station_id
    return df


def add_encoder_history_features(df: pd.DataFrame) -> pd.DataFrame:
    """Copy the canonical residual into its encoder-only model input."""
    if TARGET not in df.columns:
        raise ValueError(
            f"encoder DataFrame must have a {TARGET!r} column"
        )
    result = df.copy()
    result[HISTORICAL_TARGET_FEATURE] = result[TARGET].astype("float32")
    return result


def add_decoder_history_features(df: pd.DataFrame) -> pd.DataFrame:
    """Add a non-informative placeholder for an encoder-only model input."""
    result = df.copy()
    result[HISTORICAL_TARGET_FEATURE] = np.float32(0.0)
    return result
